import type { CanvasDocument } from "../../types/document";

/** Where a command came from. Carried unchanged into results and history. */
export type CommandOrigin = "ui" | "canvas" | "voice";

// ---------------------------------------------------------------------------
// Public commands — the only operations UI (and, later, voice) may request.
// ---------------------------------------------------------------------------

export interface ShapeCreateParams {
  shape: "rectangle" | "circle";
  x?: number;
  y?: number;
  width?: number;
  height?: number;
  rotation?: number;
  opacity?: number;
  fill?: string;
  stroke?: string;
  strokeWidth?: number;
  /** Rectangles only. */
  cornerRadius?: number;
}

export interface TextCreateParams {
  text?: string;
  x?: number;
  y?: number;
  width?: number;
  rotation?: number;
  opacity?: number;
  fill?: string;
  fontFamily?: string;
  fontSize?: number;
  fontWeight?: string | number;
  fontStyle?: "normal" | "italic";
  textAlign?: "left" | "center" | "right";
  lineHeight?: number;
  letterSpacing?: number;
}

export interface DocumentSetBackgroundParams {
  color: string;
}

export type ShapeCreateCommand = { operation: "shape.create"; parameters: ShapeCreateParams };
export type TextCreateCommand = { operation: "text.create"; parameters: TextCreateParams };
export type DocumentSetBackgroundCommand = {
  operation: "document.set_background";
  parameters: DocumentSetBackgroundParams;
};

export type PublicCommand = ShapeCreateCommand | TextCreateCommand | DocumentSetBackgroundCommand;
export type PublicOperation = PublicCommand["operation"];

// ---------------------------------------------------------------------------
// Internal commands — trusted, renderer-originated. Never part of the public
// registry or any AI allowlist; dispatched only via `dispatchInternal`.
// ---------------------------------------------------------------------------

/** Every internal command states which document state it was derived from. */
export interface InternalCommandBasis {
  /** `documentRevision` the measurement was taken against. */
  basedOnRevision: number;
  /** History head operation at measurement time (null = no history). */
  sourceOperationId: string | null;
}

export interface TextMeasurement {
  objectId: string;
  height: number;
  /** `textLayoutKey()` of the object as it was measured. */
  layoutKey: string;
}

export interface TextSyncLayoutParams extends InternalCommandBasis {
  measurements: TextMeasurement[];
}

export type TextSyncLayoutCommand = { operation: "text.sync_layout"; parameters: TextSyncLayoutParams };

export type InternalCommand = TextSyncLayoutCommand;
export type InternalOperation = InternalCommand["operation"];

export type ExecutableCommand = PublicCommand | InternalCommand;

// ---------------------------------------------------------------------------
// Requests and results
// ---------------------------------------------------------------------------

export interface CommandRequest<C extends ExecutableCommand> {
  command: C;
  origin: CommandOrigin;
  /** Generated by the dispatcher when omitted. */
  operationId?: string;
}

interface CommandResultBase {
  operationId: string;
  /** Raw operation name as requested (may be unknown/invalid on rejection). */
  operation: string;
  origin: CommandOrigin;
  /** User-facing, human-readable message. */
  message: string;
}

export type CommandResult =
  | (CommandResultBase & { status: "success"; targetIds: string[] })
  | (CommandResultBase & { status: "skipped"; targetIds: string[] })
  | (CommandResultBase & { status: "rejected"; targetIds: [] })
  | (CommandResultBase & { status: "failed"; targetIds: [] });

export type CommandStatus = CommandResult["status"];

// ---------------------------------------------------------------------------
// Handlers
// ---------------------------------------------------------------------------

export interface EngineContext {
  createId: () => string;
  now: () => string;
}

export type HandlerOutcome =
  | {
      kind: "applied";
      document: CanvasDocument;
      targetIds: string[];
      message: string;
      createdObjectId?: string;
    }
  | { kind: "skipped"; targetIds: string[]; message: string }
  | { kind: "rejected"; message: string };

export interface CommandHandler {
  /** Allowed keys in `parameters`; anything else is rejected by the engine. */
  parameterKeys: readonly string[];
  /** Validates `parameters` (untrusted) and applies the change immutably. */
  execute(document: CanvasDocument, parameters: Record<string, unknown>, ctx: EngineContext): HandlerOutcome;
}
